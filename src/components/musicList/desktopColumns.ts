/**
 * 桌面端歌曲表格的列尺寸（表头与歌曲行共用）
 *
 * 列顺序：序号 / 标题 / 专辑 / 喜欢 / 时长 / 更多。
 * 序号、喜欢、时长、更多是定宽列，标题与专辑两列按比例瓜分剩余宽度。
 * 表头和行分别渲染在不同组件里，但都读这里的数值 —— 只改一处，
 * 否则「专辑」「喜欢」「时长」三栏会和行内容对不上。
 */
export const columnSize = {
    /** 序号列（01 / 02 …） */
    index: 44,
    /** 喜欢列：只放收藏心形，表头「喜欢」与图标同列居中 */
    like: 40,
    /** 时长列 */
    duration: 56,
    /**
     * 时长列右侧的额外内边距。
     *
     * 时长右对齐，不留白时数字会紧贴右边的「更多」按钮；留 10px 让数字往里收，
     * 视觉上也更靠近左边的「喜欢」。
     * 表头与行必须同值，否则两处对不齐。
     */
    durationInset: 10,
    /**
     * 更多（⋮）列。
     *
     * 悬停该行才显示，但列宽常驻 —— 否则按钮出现/消失时「时长」会左右跳动。
     */
    more: 28,
    /**
     * 「更多」列向左平移的距离（纯视觉位移，用 transform 实现）。
     *
     * 列距统一是 gap，但时长与 ⋮ 之间按 gap 排时显得离得太远、整块偏右。
     * 这里只把 ⋮ 的显示位置往时长方向带近一点：
     * 不能用负 marginLeft —— 那会减少行内总宽，被标题/专辑两列吃掉，
     * 反而把「时长」整体推右；transform 不参与布局，其它列一动不动。
     * 表头那一列是空的，不需要跟着移。
     */
    morePull: 10,
    /** 列与列之间的间距 */
    gap: 12,
    /** 行高 */
    rowHeight: 56,
    /** 行内封面 */
    cover: 42,
    /**
     * 滚动条宽度（web/index.html 里 `::-webkit-scrollbar` 定的是 8px）。
     *
     * 表格的滚动容器强制 `overflow-y: scroll`，竖向滚动条常驻占掉这 8px，
     * 行内容的可用宽度就比表头少 8px。表头自己补上这 8px 右内边距，
     * 「喜欢」「时长」两列才会和下方行对齐；不给的话两列会整体右偏一格滚动条。
     */
    scrollbar: 8,
};

/** 标题列 : 专辑列的宽度比例 */
export const columnFlex = {
    title: 1.55,
    album: 1,
};
